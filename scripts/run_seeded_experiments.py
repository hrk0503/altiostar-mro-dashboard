#!/usr/bin/env python3
"""Run 5 seeded MRO experiments and save results to results/seeded_runs/."""

from __future__ import annotations

import argparse
import json
import logging
import shutil
import sys
from pathlib import Path

# Ensure project root is on path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from run_experiment import run_single_experiment

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    datefmt="%H:%M:%S",
)
logger = logging.getLogger(__name__)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Run 5 seeded experiments (seeds 1-5) for baseline scenario + v2 reward."
    )
    parser.add_argument(
        "--timesteps",
        type=int,
        default=50000,
        help="Training timesteps per experiment run (default: 50000)",
    )
    parser.add_argument(
        "--eval-episodes",
        type=int,
        default=5,
        help="Evaluation episodes per experiment run (default: 5)",
    )

    args = parser.parse_args()

    # Create directories
    results_dir = Path("results") / "seeded_runs"
    checkpoints_dir = Path("checkpoints") / "seeded_runs"
    results_dir.mkdir(parents=True, exist_ok=True)
    checkpoints_dir.mkdir(parents=True, exist_ok=True)

    variant = "v2"
    scenario = "baseline"
    seeds = [1, 2, 3, 4, 5]

    logger.info("=" * 60)
    logger.info("STARTING SEEDED RUNS WORKFLOW (seeds 1-5)")
    logger.info("Variant: %s | Scenario: %s", variant, scenario)
    logger.info("Timesteps: %d | Eval Episodes: %d", args.timesteps, args.eval_episodes)
    logger.info("=" * 60)

    for seed in seeds:
        logger.info("\n" + "#" * 60)
        logger.info("RUNNING SEED %d / %d (seed=%d)", seed, len(seeds), seed)
        logger.info("#" * 60)

        run_name = f"{variant}_{scenario}_seed_{seed}"

        # Execute training + evaluation + MLflow logging
        result = run_single_experiment(
            variant=variant,
            scenario=scenario,
            timesteps=args.timesteps,
            eval_episodes=args.eval_episodes,
            seed=seed,
            run_name=run_name,
        )

        # File paths generated by run_single_experiment
        temp_json_path = Path("results") / f"experiment_{run_name}.json"
        temp_model_path = Path("checkpoints") / f"ppo_{run_name}.zip"

        # Destined paths
        final_json_path = results_dir / f"experiment_{run_name}.json"
        final_model_path = checkpoints_dir / f"ppo_{run_name}.zip"

        # Move model checkpoint
        if temp_model_path.exists():
            logger.info("Moving model checkpoint to: %s", final_model_path)
            shutil.move(str(temp_model_path), str(final_model_path))
            result["training"]["checkpoint_path"] = str(final_model_path)
        else:
            logger.warning("Temporary model checkpoint not found at: %s", temp_model_path)

        # Move and update results JSON
        if temp_json_path.exists():
            # Update json file with the new checkpoint path
            with open(temp_json_path) as f:
                json_data = json.load(f)
            
            json_data["training"]["checkpoint_path"] = str(final_model_path)
            
            logger.info("Saving updated results JSON to: %s", final_json_path)
            with open(final_json_path, "w") as f:
                json.dump(json_data, f, indent=2)
            
            temp_json_path.unlink()  # remove temp file
        else:
            logger.warning("Temporary results JSON not found at: %s", temp_json_path)
            logger.info("Saving results dict directly to: %s", final_json_path)
            with open(final_json_path, "w") as f:
                json.dump(result, f, indent=2)

        logger.info("Seed %d completed successfully.", seed)

    logger.info("\n" + "=" * 60)
    logger.info("ALL 5 SEEDED RUNS COMPLETED AND LOGGED TO MLFLOW.")
    logger.info("Results saved under: %s", results_dir)
    logger.info("Checkpoints saved under: %s", checkpoints_dir)
    logger.info("=" * 60)


if __name__ == "__main__":
    main()
